using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using SkillHub.Application.Interfaces.Services;
using SkillHub.Domain.Entities;

namespace SkillHub.Infrastructure.Services;

public class PdfCertificateGenerator : IPdfCertificateGenerator
{
    static PdfCertificateGenerator()
    {
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public byte[] GenerateEnrollmentCertificate(Enrollment enrollment)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(2, Unit.Centimetre);
                page.PageColor(Colors.White);
                page.DefaultTextStyle(x => x.FontSize(11).FontColor(Colors.Grey.Darken3));

                page.Header()
                    .AlignCenter()
                    .Column(col =>
                    {
                        col.Item().Text("SKILLHUB - TRAINING CENTER")
                            .FontSize(20)
                            .Bold()
                            .FontColor(Colors.Blue.Darken2);
                        col.Item().Text("Official Workshop Enrollment Certificate")
                            .FontSize(14)
                            .SemiBold()
                            .FontColor(Colors.Grey.Darken1);
                        col.Item().PaddingTop(5).LineHorizontal(1).LineColor(Colors.Grey.Lighten2);
                    });

                page.Content()
                    .PaddingVertical(1.5f, Unit.Centimetre)
                    .Column(col =>
                    {
                        col.Spacing(15);

                        col.Item().Text(text =>
                        {
                            text.Span("This certifies that participant ");
                            text.Span(enrollment.Participant.FullName).Bold();
                            text.Span($", identified with {enrollment.Participant.Identification.Type} number ");
                            text.Span(enrollment.Participant.Identification.Number).Bold();
                            text.Span(", is formally enrolled in the following in-person workshop:");
                        });

                        col.Item().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(15).Column(details =>
                        {
                            details.Spacing(8);
                            details.Item().Text($"Workshop Code: {enrollment.Workshop.Code}").Bold();
                            details.Item().Text($"Title: {enrollment.Workshop.Title}");
                            details.Item().Text($"Assigned Instructor: {enrollment.Workshop.Instructor.FullName} ({enrollment.Workshop.Instructor.Specialty})");
                            details.Item().Text($"Start Date and Time: {enrollment.Workshop.StartAt:yyyy-MM-dd HH:mm} UTC");
                            details.Item().Text($"End Date and Time: {enrollment.Workshop.EndAt:yyyy-MM-dd HH:mm} UTC");
                            details.Item().Text($"Enrollment Status: {enrollment.Status}").Bold();
                            details.Item().Text($"Enrolled On: {enrollment.CreatedAt:yyyy-MM-dd HH:mm} UTC");
                        });

                        col.Item().Text("This certificate confirms the spot reservation for the indicated date and is subject to compliance with SkillHub regulations.");
                    });

                page.Footer()
                    .AlignCenter()
                    .Text(x =>
                    {
                        x.Span("Automatically generated by SkillHub Platform | Page ");
                        x.CurrentPageNumber();
                        x.Span(" of ");
                        x.TotalPages();
                    });
            });
        });

        return document.GeneratePdf();
    }
}
